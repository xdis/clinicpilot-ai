#!/usr/bin/env bash
# Creates observability/langfuse/.env with random secrets and a headless-initialised org, project, API keys and
# login, then writes the project keys into ai-service/.env. Never overwrites an existing Langfuse .env.
#   ./scripts/langfuse-env.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LF="$ROOT/observability/langfuse/.env"; AI="$ROOT/ai-service/.env"
if [ -f "$LF" ]; then echo "$LF already exists (delete it first to regenerate; a running Langfuse keeps its old data)"; else
python3 - "$LF" <<'PY'
import secrets, sys, uuid
pk, sk, pw = f"pk-lf-{uuid.uuid4()}", f"sk-lf-{uuid.uuid4()}", secrets.token_urlsafe(12)
open(sys.argv[1], "w").write(f"""# Generated by scripts/langfuse-env.sh: local use only (gitignored)
NEXTAUTH_URL=http://localhost:3100
NEXTAUTH_SECRET={secrets.token_hex(32)}
SALT={secrets.token_hex(16)}
ENCRYPTION_KEY={secrets.token_hex(32)}
POSTGRES_PASSWORD={secrets.token_urlsafe(16)}
DATABASE_URL=postgresql://postgres:${{POSTGRES_PASSWORD}}@postgres:5432/postgres
CLICKHOUSE_PASSWORD={secrets.token_urlsafe(16)}
REDIS_AUTH={secrets.token_urlsafe(16)}
MINIO_ROOT_PASSWORD={secrets.token_urlsafe(16)}
LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY=${{MINIO_ROOT_PASSWORD}}
LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY=${{MINIO_ROOT_PASSWORD}}
LANGFUSE_S3_BATCH_EXPORT_SECRET_ACCESS_KEY=${{MINIO_ROOT_PASSWORD}}
LANGFUSE_S3_MEDIA_UPLOAD_ENDPOINT=http://localhost:9090
LANGFUSE_INIT_ORG_ID=clinicpilot
LANGFUSE_INIT_ORG_NAME=ClinicPilot
LANGFUSE_INIT_PROJECT_ID=clinicpilot-ai
LANGFUSE_INIT_PROJECT_NAME=ClinicPilot AI
LANGFUSE_INIT_PROJECT_PUBLIC_KEY={pk}
LANGFUSE_INIT_PROJECT_SECRET_KEY={sk}
LANGFUSE_INIT_USER_EMAIL=demo@clinicpilot.local
LANGFUSE_INIT_USER_NAME=ClinicPilot Demo
LANGFUSE_INIT_USER_PASSWORD={pw}
""")
PY
echo "created $LF"; fi
PK=$(grep ^LANGFUSE_INIT_PROJECT_PUBLIC_KEY= "$LF" | cut -d= -f2); SK=$(grep ^LANGFUSE_INIT_PROJECT_SECRET_KEY= "$LF" | cut -d= -f2)
[ -f "$AI" ] || cp "$ROOT/ai-service/.env.example" "$AI"
python3 - "$AI" "$PK" "$SK" <<'PY'
import re, sys
p, pk, sk = sys.argv[1:]
s = open(p).read()
for k, v in (("LANGFUSE_PUBLIC_KEY", pk), ("LANGFUSE_SECRET_KEY", sk), ("LANGFUSE_HOST", "http://localhost:3100")):
    s = re.sub(rf"^#?\s*{k}=.*$", f"{k}={v}", s, flags=re.M) if re.search(rf"^#?\s*{k}=", s, re.M) else s.rstrip("\n") + f"\n{k}={v}\n"
open(p, "w").write(s)
PY
echo "ai-service/.env: Langfuse keys set. Login: $(grep ^LANGFUSE_INIT_USER_EMAIL= "$LF" | cut -d= -f2) / $(grep ^LANGFUSE_INIT_USER_PASSWORD= "$LF" | cut -d= -f2)"
